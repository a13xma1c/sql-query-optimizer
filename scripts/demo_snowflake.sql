CREATE TABLE customers (id NUMBER(10,0), name VARCHAR, region VARCHAR, signup_date DATE, email VARCHAR);
CREATE TABLE products (id NUMBER(10,0), sku VARCHAR(16), category VARCHAR, price NUMBER(10,2));
CREATE TABLE orders (id NUMBER(10,0), customer_id NUMBER(10,0), ts TIMESTAMP_NTZ, status VARCHAR, amount NUMBER(10,0)) CLUSTER BY (ts);
CREATE TABLE order_items (order_id NUMBER(10,0), product_id NUMBER(10,0), quantity NUMBER(10,0), price NUMBER(10,2));
CREATE TABLE refunds (order_id NUMBER(10,0), amt NUMBER(10,0), reason VARCHAR);
CREATE TABLE shipments (id NUMBER(10,0), order_ref VARCHAR(16), shipped_at TIMESTAMP_NTZ, carrier VARCHAR);
CREATE TABLE events (id NUMBER(19,0), dt DATE, user_id NUMBER(10,0), kind VARCHAR) CLUSTER BY (dt);

